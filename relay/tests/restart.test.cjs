const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

test('server restart restores queued, attempted, replied and retry state without duplicate sends', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'relay-restart-'));
  let relay;
  t.after(async () => { if (relay) await relay.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  const [{ startServer }, { DeliveryCoordinator }] = await Promise.all([
    import('../dist/src/server.js'), import('../dist/src/delivery.js'),
  ]);
  relay = await startServer({ port: 0, dataDir: dir, startDelivery: false });
  relay.sessions.register({ id: 'source', provider: 'codex', providerSessionId: 'source-thread', cwd: dir });
  relay.sessions.register({ id: 'target', provider: 'codex', providerSessionId: 'target-thread', cwd: dir });
  const make = question => relay.exchanges.send('source', { targetSessionId: 'target', question });
  const queued = make('queued');
  const attempted = make('attempted');
  relay.exchanges.recordAttempt(attempted.id, 'target', 'request', 'codex_queue', 'sent', 'queue accepted');
  const attemptedRetry = make('attempted retry');
  relay.exchanges.recordAttempt(attemptedRetry.id, 'target', 'request', 'codex_queue', 'sent', 'queue accepted');
  relay.exchanges.requestRetry(attemptedRetry.id, 'source', 'request');
  const replied = make('replied');
  relay.exchanges.receive(replied.id, 'target');
  relay.exchanges.reply(replied.id, 'target', 'answer');
  const repliedSent = make('replied sent');
  relay.exchanges.receive(repliedSent.id, 'target');
  relay.exchanges.reply(repliedSent.id, 'target', 'answer');
  relay.exchanges.recordAttempt(repliedSent.id, 'source', 'answer', 'codex_queue', 'sent', 'answer queued');
  const repliedRetry = make('replied retry');
  relay.exchanges.receive(repliedRetry.id, 'target');
  relay.exchanges.reply(repliedRetry.id, 'target', 'answer');
  relay.exchanges.recordAttempt(repliedRetry.id, 'source', 'answer', 'codex_queue', 'sent', 'answer queued');
  relay.exchanges.requestRetry(repliedRetry.id, 'target', 'answer');
  const limited = make('two failures');
  relay.exchanges.recordAttempt(limited.id, 'target', 'request', 'codex_queue', 'failed', 'failure 1');
  relay.exchanges.recordAttempt(limited.id, 'target', 'request', 'codex_queue', 'failed', 'failure 2');
  await relay.close();
  relay = undefined;
  relay = await startServer({ port: 0, dataDir: dir, startDelivery: false });
  const restored = new Map(relay.exchanges.all().map(row => [row.id, row]));
  assert.equal(restored.get(queued.id).status, 'queued');
  assert.equal(restored.get(attempted.id).status, 'delivery_attempted');
  assert.equal(restored.get(attemptedRetry.id).retryRequested.request, true);
  assert.equal(restored.get(replied.id).status, 'replied');
  assert.equal(restored.get(repliedSent.id).attempts.length, 1);
  assert.equal(restored.get(repliedRetry.id).retryRequested.answer, true);
  assert.equal(restored.get(limited.id).attempts.length, 2);
  const calls = [];
  const coordinator = new DeliveryCoordinator(relay.sessions, relay.exchanges, 'codex', async (_binary, thread, message) => {
    calls.push({ thread, message });
    return { ok: true, detail: 'queue accepted; receipt unconfirmed' };
  });
  await coordinator.tick();
  const after = new Map(relay.exchanges.all().map(row => [row.id, row]));
  assert.equal(calls.length, 4);
  assert.equal(after.get(queued.id).status, 'delivery_attempted');
  assert.equal(after.get(attempted.id).attempts.length, 1);
  assert.equal(after.get(attemptedRetry.id).attempts.at(-1).trigger, 'explicit');
  assert.equal(after.get(attemptedRetry.id).retryRequested.request, false);
  assert.equal(after.get(replied.id).status, 'replied');
  assert.equal(after.get(replied.id).attempts.at(-1).direction, 'answer');
  assert.equal(after.get(repliedSent.id).attempts.length, 1);
  assert.equal(after.get(repliedRetry.id).attempts.at(-1).trigger, 'explicit');
  assert.equal(after.get(repliedRetry.id).retryRequested.answer, false);
  assert.equal(after.get(limited.id).attempts.length, 2);
  relay.exchanges.requestRetry(repliedSent.id, 'target', 'answer');
  await coordinator.tick();
  const resent = relay.exchanges.all().find(row => row.id === repliedSent.id);
  assert.equal(resent.attempts.at(-1).trigger, 'explicit');
  assert.equal(resent.status, 'replied');
});
